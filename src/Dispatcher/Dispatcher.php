/**
 * Dispatcher class for mod_multiblock
 *
 * @since  4.4.0
 */
class Dispatcher extends AbstractModuleDispatcher implements HelperFactoryAwareInterface
{
    use HelperFactoryAwareTrait;

    /**
     * Returns the layout data.
     *
     * @return  array
     *
     * @since   4.4.0
     */
    protected function getLayoutData(): array
    {
        $data = parent::getLayoutData();

        $data['list'] = $this->getHelperFactory()->getHelper('MultiblockHelper')->getModuleData($data['params'], $data['app']);

        //if (($data['params'])->get('prepare_content', 1)) {
            //($data['module'])->edt_2 = HTMLHelper::_('content.prepare', ($data['module'])->edt_, '', 'mod_multiblock.content');
        //}
				

        return $data;
    }
}
